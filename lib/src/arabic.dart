/// Lam and each alef after it, as their ligature: alone, joined to the one
/// before.
const _lamAlef = <int, List<int>>{
  0x0622: [0xFEF5, 0xFEF6],
  0x0623: [0xFEF7, 0xFEF8],
  0x0625: [0xFEF9, 0xFEFA],
  0x0627: [0xFEFB, 0xFEFC],
};

const _tatweel = 0x0640, _lam = 0x0644;

bool _mark(int c) => (c >= 0x064B && c <= 0x065F) || c == 0x0670 || (c >= 0x06D6 && c <= 0x06ED);

/// Whether the letter reaches on to join the next.
bool _joinsOn(int c) => c == _tatweel || (_forms[c]?[2] ?? 0) != 0;

/// Whether the letter can be joined from the one before it.
bool _joinable(int c) => c == _tatweel || (_forms[c]?[1] ?? 0) != 0;

/// Whether [line] reads right to left: its first letter is Arabic.
bool isRightToLeft(String line) {
  for (final c in line.runes) {
    if ((c >= 0x0600 && c <= 0x08FF) || (c >= 0xFB50 && c <= 0xFDFF) || (c >= 0xFE70 && c <= 0xFEFF)) return true;
    if ((c >= 0x41 && c <= 0x5A) || (c >= 0x61 && c <= 0x7A) || (c >= 0xC0 && c <= 0x2AF)) return false;
  }
  return false;
}

/// [line] with its Arabic letters in the forms they take joined to their
/// neighbours (lam-alef as the ligature), its vowel marks left out: one glyph a
/// character, in the order they're written. [joined] says, for each, whether
/// it joins on to the next.
({String text, List<bool> joined}) arabicShaped(String line) {
  final cs = [
    for (final r in line.runes)
      if (!_mark(r)) r
  ];
  final out = <int>[], joined = <bool>[];
  for (var i = 0; i < cs.length; i++) {
    final c = cs[i];
    final after = i > 0 && _joinsOn(cs[i - 1]);
    if (c == _lam && i + 1 < cs.length && _lamAlef.containsKey(cs[i + 1])) {
      out.add(_lamAlef[cs[i + 1]]![after ? 1 : 0]);
      joined.add(false);
      i++;
      continue;
    }
    final f = _forms[c];
    if (f == null) {
      out.add(c);
      joined.add(c == _tatweel && i + 1 < cs.length && _joinable(cs[i + 1]));
      continue;
    }
    final back = after && f[1] != 0;
    final on = f[2] != 0 && i + 1 < cs.length && _joinable(cs[i + 1]);
    final form = back ? (on ? 3 : 1) : (on ? 2 : 0);
    out.add(f[form] != 0 ? f[form] : f[0]);
    joined.add(on);
  }
  return (text: String.fromCharCodes(out), joined: joined);
}
