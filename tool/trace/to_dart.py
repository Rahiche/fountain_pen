"""to_dart.py <strokes.json> <out.dart> <name> <font> <license>: a traced
hand (strokes.py's JSON) as a Dart constant, `const <name> = PenHand(...)`.

    python3 tool/trace/to_dart.py work/strokes.json lib/src/hands/my_hand.dart \\
        myHand "My Font" "Licensed under the SIL Open Font License 1.1"
"""
import json, sys

src, out, name, font, license_ = sys.argv[1:6]
d = json.load(open(src))


def key(c):
    if c.isalnum() or c in ' .,!?-:;()&*+/<=>@[]^_`{|}~#%':
        return "'" + c + "'"
    return "'\\u{%x}'" % ord(c)


def num(v):
    s = ('%.4f' % v).rstrip('0').rstrip('.')
    return '0' if s in ('-0', '') else s


lines = [
    f'// Generated by tool/trace/to_dart.py from {font}: each glyph\'s pen strokes,',
    '// traced from the font\'s outlines (tool/trace/strokes.py). Do not edit.',
    f'// {font}: {license_}',
    '',
    "import '../hand.dart';",
    '',
    f'/// A hand traced from {font} (Basic Latin).',
    f'const {name} = PenHand(xHeight: {num(d["xHeight"])}, space: {num(d["space"])}, glyphs: {{',
]
for c, g in d['glyphs'].items():
    strokes = []
    for s in g['strokes']:
        flags = (', late: true' if s['late'] else '') + (', dot: true' if s.get('dot') else '')
        strokes.append(f"PenStroke([{', '.join(num(v) for v in s['p'])}]{flags})")
    lines.append(f"  {key(c)}: PenGlyph({num(g['adv'])}, [{', '.join(strokes)}]),")
lines.append('});')
open(out, 'w').write('\n'.join(lines) + '\n')
print(out, f"{len(d['glyphs'])} glyphs")
