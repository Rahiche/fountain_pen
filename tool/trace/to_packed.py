"""to_packed.py <strokes.json> <out.dart> <name> <font> <notice>: a traced
hand (strokes.json, from strokes.py or strokes_cjk.py) packed into a Dart
file, `final <name> = PenHand.packed(...)`: for hands with thousands of
glyphs, too many to write out as constants. Each glyph is unpacked the
first time it's written; a hand an app never uses is left out of it.

The format is PenHand.packed's (lib/src/hand.dart): points to 1/512 em,
each after the first as a step from the last; one width per stroke.

    python3 tool/trace/to_packed.py work/strokes.json lib/src/hands/my_hand.dart \\
        myHand "My Font" "Copyright ... Licensed under the SIL Open Font License 1.1"
"""
import base64, json, sys

src, out, name, font, notice = sys.argv[1:6]
d = json.load(open(src))


def varint(v):
    b = bytearray()
    while True:
        if v < 0x80:
            b.append(v)
            return bytes(b)
        b.append((v & 0x7f) | 0x80)
        v >>= 7


def zigzag(v):
    return varint(v * 2 if v >= 0 else -v * 2 - 1)


def u16(v):
    v = max(0, min(0xffff, int(round(v))))
    return bytes([v & 0xff, v >> 8])


codes, bodies = [], []
for c, g in sorted(d['glyphs'].items(), key=lambda kv: ord(kv[0])):
    if len(c) != 1:
        continue
    body = bytearray(u16(g['adv'] * 10000))
    body += varint(len(g['strokes']))
    for s in g['strokes']:
        p = s['p']
        pts = [(p[i], p[i + 1], p[i + 2]) for i in range(0, len(p) - 2, 3)]
        r = sorted(q[2] for q in pts)[len(pts) // 2] if pts else 0
        body.append((1 if s.get('late') else 0) | (2 if s.get('dot') else 0))
        body += varint(len(pts))
        body.append(max(0, min(255, int(round(r * 1024)))))
        x = y = 0
        for (px, py, _) in pts:
            qx, qy = int(round(px * 512)), int(round(py * 512))
            body += zigzag(qx - x) + zigzag(qy - y)
            x, y = qx, qy
    codes.append(ord(c))
    bodies.append(bytes(body))

blob = bytearray(b'FPH\x01')
blob += u16(d['xHeight'] * 10000) + u16(d.get('space', 0.5) * 10000)
blob += varint(len(codes))
last = 0
for c, b in zip(codes, bodies):
    blob += varint(c - last) + varint(len(b))
    last = c
for b in bodies:
    blob += b
text = base64.b64encode(bytes(blob)).decode()
parts = [text[i:i + 100000] for i in range(0, len(text), 100000)]
lines = [
    f'// Generated by tool/trace/to_packed.py from {font}: each glyph\'s pen strokes,',
    '// traced from the font\'s outlines, packed (PenHand.packed). Do not edit.',
    f'// {notice}',
    '',
    "import '../hand.dart';",
    '',
    f'/// A hand traced from {font}: {len(codes)} characters.',
    f'final PenHand {name} = PenHand.packed(_data);',
    '',
    'const _data = [',
] + [f"  '{q}'," for q in parts] + ['];']
open(out, 'w').write('\n'.join(lines) + '\n')
print(out, f'{len(codes)} glyphs, {len(blob) / 1e6:.2f} MB packed, {len(text) / 1e6:.2f} MB of base64')
